# The floppy drive's recordings -> engine/android/vt_samples.h: mono, 44.1 kHz, 16-bit, each brought to the same peak,
# with 5 ms fades at either end. Needs ffmpeg.   python3 engine/android/sounds/make_header.py
import os, subprocess, struct
HERE = os.path.dirname(os.path.abspath(__file__))
PEAK = 9800                                    # (about a third of full scale: under the synth's own level)
out = ['/* generated by sounds/make_header.py from sounds/*.wav: floppy drive recordings by ullvieib (freesound.org),',
       ' * CC BY 4.0. Mono, 44.1 kHz. Do not edit. */']
for name in ('DISK1', 'DISK3', 'DISKSAVE'):
    raw = subprocess.run(['ffmpeg', '-loglevel', 'error', '-i', os.path.join(HERE, name + '.wav'),
                          '-ar', '44100', '-ac', '1', '-f', 's16le', '-'], capture_output=True, check=True).stdout
    s = list(struct.unpack('<%dh' % (len(raw) // 2), raw))
    pk = max(abs(v) for v in s) or 1
    f = 220
    s = [round(v * PEAK / pk * min(1.0, i / f, (len(s) - 1 - i) / f)) for i, v in enumerate(s)]
    out.append('static const int16_t VT_%s[%d] = {' % (name, len(s)))
    for i in range(0, len(s), 24):
        out.append('    ' + ','.join(str(v) for v in s[i:i + 24]) + ',')
    out.append('};')
open(os.path.join(HERE, '..', 'vt_samples.h'), 'w').write('\n'.join(out) + '\n')
